const FORBIDDEN_KEY = /allerg|contain|free|safe|suitab|vegan|nut/i;
/** Every path whose last key matches FORBIDDEN_KEY, at any depth, pushed onto `out`. */
function forbiddenKeys(value, path, out) {
    if (!value || typeof value !== 'object')
        return out;
    if (Array.isArray(value)) {
        for (let i = 0; i < value.length; i++)
            forbiddenKeys(value[i], path + '[' + i + ']', out);
        return out;
    }
    const keys = Object.keys(value);
    for (let k = 0; k < keys.length; k++) {
        if (FORBIDDEN_KEY.test(keys[k]))
            out.push(path + '.' + keys[k]);
        forbiddenKeys(value[keys[k]], path + '.' + keys[k], out);
    }
    return out;
}
