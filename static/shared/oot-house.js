/** The marks and kept a row's block carries that this projection shares, screened by shape. */
function readBlock(block, marks) {
    const out = {};
    if (!block || typeof block !== 'object' || Array.isArray(block))
        return out;
    const b = block;
    for (const f of marks)
        if (isMark(b[f]))
            out[f] = b[f];
    const kept = Array.isArray(b.kept) ? b.kept.filter(isNote) : [];
    if (kept.length)
        out.kept = kept;
    return out;
}
/** The marks on a block or an item, each the same mark with its value copied, so a row and an item never share one list. */
function copyMark(m) {
    const value = Array.isArray(m.value) ? m.value.slice() : m.value && typeof m.value === 'object' ? Object.assign({}, m.value) : m.value;
    const out = { value, by: m.by, ts: m.ts };
    if (m.model !== undefined)
        out.model = m.model;
    return out;
}
/**
 * The four doors from one description. toRow starts from the previous row
 * so every field of the wing's own rides through untouched, then writes the
 * shared fields, the stamp and the block; a key the row had keeps its place,
 * so a row written twice is the same bytes. fromRow starts from the blank
 * house-only fields and reads only what the description names.
 */
function adapterFrom(spec) {
    const toRow = (item, prevRow) => {
        const it = item;
        const out = prevRow ? Object.assign({}, prevRow) : {};
        out.id = item.id;
        if (spec.houseAlways || item.house)
            out.house = item.house;
        else
            delete out.house;
        for (const f of spec.shared)
            out[f.row] = f.out ? f.out(it[f.item]) : it[f.item];
        out.ts = item.ts;
        const block = prevRow && prevRow.maitre && typeof prevRow.maitre === 'object' ? Object.assign({}, prevRow.maitre) : {};
        for (const f of spec.marks) {
            if (isMark(it[f]))
                block[f] = copyMark(it[f]);
            else
                delete block[f];
        }
        const kept = Array.isArray(it.kept) ? it.kept.filter(isNote).map((n) => (Object.assign({}, n))) : [];
        if (kept.length)
            block.kept = kept;
        else
            delete block.kept;
        if (Object.keys(block).length)
            out.maitre = block;
        else
            delete out.maitre;
        const row = out;
        return spec.finish ? spec.finish(row) : row;
    };
    const fromRow = (row, ref) => {
        const out = Object.assign({ id: row.id, house: rowText(row.house), kind: spec.kind, name: '' }, spec.blank(row));
        const refFields = ref;
        for (const f of spec.shared) {
            const raw = row[f.row];
            /* The reference's value, when the row holds that value written out:
               the text is the same, so the reading must be the same. */
            if (refFields && f.out && f.item in refFields && sameJson(f.out(refFields[f.item]), raw)) {
                const v = refFields[f.item];
                out[f.item] = Array.isArray(v) ? v.slice() : v;
            }
            else
                out[f.item] = f.in ? f.in(raw) : rowText(raw);
        }
        if (spec.derive)
            Object.assign(out, spec.derive(row));
        const block = readBlock(row.maitre, spec.marks);
        for (const f of spec.marks)
            if (isMark(block[f]))
                out[f] = copyMark(block[f]);
        if (block.kept)
            out.kept = block.kept.map((n) => (Object.assign({}, n)));
        out.ts = rowStamp(row.ts);
        return out;
    };
    /* lastTouch's rule over the row's whole block, not the shared marks alone:
       the Ledger keeps her marks on method, glass and garnish there, and a
       person's keep on one of them is a touch the tombstone rule must see. */
    const rowTouch = (row) => {
        let t = rowStamp(row.ts);
        const block = row.maitre;
        if (!block || typeof block !== 'object' || Array.isArray(block))
            return t;
        const b = block;
        for (const f of Object.keys(b)) {
            const m = b[f];
            if (isMark(m) && m.by === 'person' && m.ts > t)
                t = m.ts;
        }
        if (Array.isArray(b.kept))
            for (const n of b.kept)
                if (isNote(n) && n.ts > t)
                    t = n.ts;
        return t;
    };
    const derived = spec.derive ? Object.keys(spec.derive({ id: '', ts: 0 })) : [];
    return {
        kind: spec.kind,
        shared: [...spec.shared.map((f) => f.item), ...derived],
        marks: spec.marks,
        toRow,
        fromRow,
        rowTouch,
        rename: (row, newId) => (Object.assign(Object.assign({}, row), { id: newId })),
        foldName: spec.foldName,
        rowKey: (row) => spec.foldName(spec.rowName(row)),
        itemKey: (item) => spec.foldName(spec.itemName(item))
    };
}
