/** Every string at every depth, with its path in the client's spelling: house.dishes[0].lines.value.s45. */
function eachString(value, path, visit) {
    if (typeof value === 'string') {
        visit(path, value);
        return;
    }
    if (!value || typeof value !== 'object')
        return;
    if (Array.isArray(value)) {
        for (let i = 0; i < value.length; i++)
            eachString(value[i], path + '[' + i + ']', visit);
        return;
    }
    for (const k of Object.keys(value))
        eachString(value[k], path + '.' + k, visit);
}
const ITEM_LISTS = ['dishes', 'wines', 'cocktails'];
/** Every dish, wine and cocktail with its path and list. */
function eachItem(house, visit) {
    for (const list of ITEM_LISTS) {
        const rows = listOf(house, list);
        for (let i = 0; i < rows.length; i++)
            visit(rows[i], 'house.' + list + '[' + i + ']', list);
    }
}
/** Every mark on the house (the card's history and every mark field of every list), with its path and the record it sits on. */
function eachMark(house, visit) {
    const card = house;
    for (const field of MARK_FIELDS.house) {
        const m = card[field];
        if (isMark(m))
            visit(m, 'house.' + field, card, 'house');
    }
    for (const list of HOUSE_LISTS) {
        const fields = MARK_FIELDS[list];
        if (!fields.length)
            continue;
        const rows = listOf(house, list);
        for (let i = 0; i < rows.length; i++) {
            for (const field of fields) {
                const m = rows[i][field];
                if (isMark(m))
                    visit(m, 'house.' + list + '[' + i + '].' + field, rows[i], list);
            }
        }
    }
}
function idSet(rows) {
    const out = new Set();
    for (const r of rows)
        if (typeof r.id === 'string')
            out.add(r.id);
    return out;
}
