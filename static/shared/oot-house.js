/* The app the pack is stamped from: the path the script was loaded on. */
function ootHouseFrom() {
	var p = '';
	try {
		p = ootHouseRoot.location && typeof ootHouseRoot.location.pathname === 'string' ? ootHouseRoot.location.pathname : '';
	} catch (e) {
		p = '';
	}
	if (p.indexOf('/ledger/') === 0) return 'ledger';
	if (p.indexOf('/codex/') === 0) return 'codex';
	return 'table';
}
function ootHouseInstall() {
	var volatile = !ootHouseHasIndexedDb();
	var storage = volatile ? mapStorage() : idbStorage(ootHouseRoot);
	var win = typeof ootHouseRoot.addEventListener === 'function' ? ootHouseRoot : null;
	var api = createHouseApi(storage, { win: win, from: ootHouseFrom() });
	if (volatile) api.volatile = true;
	return api;
}
