        mustKnows: asList(r.mustKnows).map((k, i) => normaliseMustKnow(k, i, ctx)),
        askAtLineup: asList(r.askAtLineup).map((a, i) => normaliseAsk(a, i, ctx)),
        disputes: asList(r.disputes).map((u, i) => normaliseDispute(u, i, ctx)),
