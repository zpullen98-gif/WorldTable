/** A stamp: a finite number, a string that reads as one, else 0. */
function asStamp(v) {
    if (typeof v === 'number')
        return Number.isFinite(v) ? v : 0;
    if (typeof v === 'string' && v.trim()) {
        const n = Number(v);
        return Number.isFinite(n) ? n : 0;
    }
    return 0;
}
