/**
 * Every reference in the house pointed through the rename map. An old id
 * still held by another item (the first of two duplicates keeps it) is not
 * mapped, so its references stay with the item that kept the id.
 */
function applyRenames(house, ctx) {
    if (!ctx.renamed.length)
        return;
    const map = new Map();
    for (const r of ctx.renamed)
        if (!ctx.taken.has(r.old) && !map.has(r.old))
            map.set(r.old, r.fresh);
    if (!map.size)
        return;
    const one = (id) => (map.has(id) ? map.get(id) : id);
    const many = (ids) => ids.map(one);
    for (const d of house.dishes) {
        if (!d.pairing)
            continue;
        const p = d.pairing.value;
        p.wineId = one(p.wineId);
        p.secondId = one(p.secondId);
        p.zeroProofId = one(p.zeroProofId);
    }
    for (const w of house.wines)
        if (w.firstPickIds)
            w.firstPickIds.value = many(w.firstPickIds.value);
    for (const c of house.cocktails)
        if (c.upsells)
            c.upsells.value = many(c.upsells.value);
    for (const t of house.tastings) {
        for (const c of t.courses) {
            c.dishIds = many(c.dishIds);
            c.pourId = one(c.pourId);
        }
    }
    for (const x of house.lexicon)
        x.itemIds = many(x.itemIds);
    for (const s of house.scenarios)
        s.itemIds = many(s.itemIds);
    for (const m of house.mixUps) {
        m.aId = one(m.aId);
        m.bId = one(m.bId);
    }
    for (const a of house.askAtLineup)
        a.itemIds = many(a.itemIds);
    for (const u of house.disputes)
        if (u.itemId)
            u.itemId = one(u.itemId);
}
