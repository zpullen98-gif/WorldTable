// Carry the reviewed fall artwork catalogue and exact WebP renditions to the Ledger.
// node tools/port-fall-menu-art.mjs [--check] [--ledger C:/path/to/BartendersLedger]
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2), at = args.indexOf('--ledger');
const ledger = at < 0 ? resolve(root, '../BartendersLedger') : resolve(args[at + 1]);
const check = args.includes('--check');
const data = JSON.parse(readFileSync(resolve(root, 'src/lib/data/fall-menu-art-2026.json'), 'utf8'));
const menu = JSON.parse(readFileSync(resolve(root, 'src/lib/data/fall-menu-2026.json'), 'utf8'));
if (data.items.length !== menu.items.length || new Set(data.items.map(x => x.itemId)).size !== menu.items.length) throw Error('Every fall item needs one reviewed study.');
const ids = new Set(menu.items.map(x => x.id));
for (const item of data.items) {
	if (!ids.has(item.itemId)) throw Error('Unknown fall item: ' + item.itemId);
	for (const path of [item.src, item.thumbnailSrc]) {
		if (!/^img\/fall-2026\/[a-z0-9-]+-v[1-9]\d*(?:\.thumb)?\.webp$/.test(path)) throw Error('Unexpected artwork path: ' + path);
		const source = resolve(root, 'static/house/brennans/fall-' + basename(path));
		const target = resolve(ledger, path);
		if (!existsSync(source)) throw Error('Missing reviewed artwork: ' + source);
		if (check) {
			if (!existsSync(target) || !readFileSync(source).equals(readFileSync(target))) throw Error('Artwork differs: ' + path);
		} else { mkdirSync(dirname(target), { recursive: true }); copyFileSync(source, target); }
	}
}
const code = '// Generated by WorldTable/tools/port-fall-menu-art.mjs. Edit the reviewed catalogue, then regenerate.\nvar FALL_MENU_ART = ' + JSON.stringify(data, null, 2) + ';\n';
const target = resolve(ledger, 'js/data-fall-menu-art.js');
if (check) {
	if (readFileSync(target, 'utf8') !== code) throw Error('Fall artwork catalogue differs.');
} else writeFileSync(target, code);
console.log(`${check ? 'Verified' : 'Carried'} ${data.items.length} teaching studies and ${data.items.length * 2} exact image files.`);
