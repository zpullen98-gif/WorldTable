// The seasonal curriculum is authored once; the classic-script Ledger consumes this exact data.
// node tools/port-fall-menu.mjs [--check] [--ledger C:/path/to/BartendersLedger]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const at = args.indexOf('--ledger');
const ledger = at >= 0 ? resolve(args[at + 1]) : resolve(root, '../BartendersLedger');
const data = JSON.parse(readFileSync(resolve(root, 'src/lib/data/fall-menu-2026.json'), 'utf8'));
const code = '// Generated by WorldTable/tools/port-fall-menu.mjs. Edit the canonical JSON, then regenerate.\nvar FALL_MENU_2026 = ' + JSON.stringify(data, null, 2) + ';\n';
const target = resolve(ledger, 'js/data-fall-menu.js');
if (args.includes('--check')) {
	if (readFileSync(target, 'utf8') !== code) throw new Error('Ledger seasonal data differs from the canonical WorldTable collection. Run port-fall-menu.mjs.');
	console.log('Fall collection matches in both apps.');
} else {
	writeFileSync(target, code);
	console.log(`Wrote ${data.items.length} seasonal items to ${target}`);
}
